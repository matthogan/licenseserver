const minimumVersion = "0.5.12"
const generatedHeader = "# Generated by licd; do not edit.\n"

var versionPattern = regexp.MustCompile(`(?i)\bv?([0-9]+)\.([0-9]+)\.([0-9]+)(?:[-+][0-9A-Za-z.-]+)?\b`)

type Health struct {
	Enabled     bool       `json:"enabled"`
	Required    bool       `json:"required"`
	Running     bool       `json:"running"`
	Status      string     `json:"status"`
	Encryption  string     `json:"encryption,omitempty"`
	LocalTXID   string     `json:"local_txid,omitempty"`
	ReplicaTXID string     `json:"replica_txid,omitempty"`
	RecoveryAt  *time.Time `json:"recovery_point_at,omitempty"`
	LastSuccess *time.Time `json:"last_success_at,omitempty"`
	LastChecked *time.Time `json:"last_checked_at,omitempty"`
	Error       string     `json:"error,omitempty"`
}

type Manager struct {
	cfg        config.Config
	logger     *slog.Logger
	database   string
	configPath string

	mu     sync.RWMutex
	health Health
	cmd    *exec.Cmd
	done   chan error
	stop   sync.Once
}

func New(cfg config.Config, logger *slog.Logger) *Manager {
	return &Manager{cfg: cfg, logger: logger, health: Health{
		Enabled: cfg.Backup.Continuous.Enabled, Required: cfg.Backup.Continuous.Required,
		Status: "disabled", Encryption: cfg.Backup.Continuous.S3.Encryption.Mode,
	}}
}

func (m *Manager) Start(ctx context.Context) error {
	if !m.cfg.Backup.Continuous.Enabled {
		return nil
	}
	database, err := filepath.Abs(m.cfg.Database.DSN)
	if err != nil {
		return fmt.Errorf("resolve database path: %w", err)
	}
	m.database = database
	m.configPath = ManagedConfigPath(m.cfg, database)
	if _, err = CheckVersion(ctx, m.cfg.Backup.Continuous.Binary); err != nil {
		return err
	}
	if err = WriteConfig(m.configPath, m.cfg, database); err != nil {
		return fmt.Errorf("write managed Litestream config: %w", err)
	}
	if err = checkConfigFile(ctx, m.cfg.Backup.Continuous.Binary, m.configPath); err != nil {
		return err
	}
	cmd := exec.Command(m.cfg.Backup.Continuous.Binary, "replicate", "-config", m.configPath)
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return err
	}
	stderr, err := cmd.StderrPipe()
	if err != nil {
		return err
	}
	if err = cmd.Start(); err != nil {
		return fmt.Errorf("start Litestream: %w", err)
	}
	m.mu.Lock()
	m.cmd = cmd
	m.done = make(chan error, 1)
	m.health.Running = true
	m.health.Status = "initializing"
	m.mu.Unlock()
	go m.logOutput("stdout", stdout)
	go m.logOutput("stderr", stderr)
	go func() {
		err := cmd.Wait()
		m.mu.Lock()
		m.health.Running = false
		if err != nil {
			m.health.Status = "error"
			m.health.Error = err.Error()
		} else {
			m.health.Status = "stopped"
		}
		m.mu.Unlock()
		m.done <- err
	}()
	go m.healthLoop(ctx)
	return nil
}

func (m *Manager) Errors() <-chan error {
	m.mu.RLock()
	defer m.mu.RUnlock()
	return m.done
}

func (m *Manager) Stop(ctx context.Context) error {
	if !m.cfg.Backup.Continuous.Enabled {
		return nil
	}
	var result error
	m.stop.Do(func() {
		m.mu.RLock()
		cmd, done, running := m.cmd, m.done, m.health.Running
		m.mu.RUnlock()
		if cmd == nil || cmd.Process == nil || !running {
			return
		}
		if err := signalGraceful(cmd.Process); err != nil {
			m.logger.Warn("Litestream graceful stop unavailable", "event", "backup.stop", "result", "failure", "reason_code", "graceful_stop_unavailable", "error", err)
			_ = cmd.Process.Kill()
		}
		select {
		case <-done:
			if requiresFinalSync() {
				if _, err := runOutput(ctx, m.cfg.Backup.Continuous.Binary, "replicate", "-config", m.configPath, "-once"); err != nil {
					result = fmt.Errorf("final Litestream sync: %w", err)
				}
			}
		case <-ctx.Done():
			_ = cmd.Process.Kill()
			result = ctx.Err()
		}
	})
	return result
}

func (m *Manager) Health() Health {
	m.mu.RLock()
	h := m.health
	m.mu.RUnlock()
	if h.Enabled && h.LastSuccess != nil && time.Since(*h.LastSuccess) > m.cfg.Backup.Continuous.MaxBackupAge {
		h.Status = "stale"
		h.Error = "last verified current replica exceeds max_backup_age"
	}
	return h
}

func (m *Manager) Ready() bool {
	h := m.Health()
	return !h.Enabled || !h.Required || h.Running && h.Status == "ok"
}

func (m *Manager) healthLoop(ctx context.Context) {
	interval := m.cfg.Backup.Continuous.HealthCheckInterval
	timer := time.NewTimer(500 * time.Millisecond)
	defer timer.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-timer.C:
			m.probe(ctx)
			timer.Reset(interval)
		}
	}
}

type ltxFile struct {
	MaxTXID   string    `json:"max_txid"`
	Timestamp time.Time `json:"timestamp"`
}

type localStatus struct {
	Status    string `json:"status"`
	LocalTXID string `json:"local_txid"`
}

func (m *Manager) probe(parent context.Context) {
	ctx, cancel := context.WithTimeout(parent, minDuration(m.cfg.Backup.Continuous.HealthCheckInterval, 30*time.Second))
	defer cancel()
	var out []byte
	var err error
	for level := 0; level <= 9; level++ {
		out, err = runOutput(ctx, m.cfg.Backup.Continuous.Binary, "ltx", "-config", m.configPath, "-level", strconv.Itoa(level), "-json", m.database)
		if err != nil || strings.TrimSpace(string(out)) != "[]" {
			break
		}
	}
	now := time.Now().UTC()
	m.mu.Lock()
	defer m.mu.Unlock()
	m.health.LastChecked = &now
	if err != nil {
		m.health.Status = "error"
		m.health.Error = err.Error()
		return
	}
	var files []ltxFile
	if err = json.Unmarshal(out, &files); err != nil {
		m.health.Status = "error"
		m.health.Error = "parse Litestream LTX status: " + err.Error()
		return
	}
	if len(files) == 0 {
		m.health.Status = "initializing"
		m.health.Error = "no remotely visible LTX backup yet"
		return
	}
	statusOutput, err := runOutput(ctx, m.cfg.Backup.Continuous.Binary, "status", "-config", m.configPath, "-json", m.database)
	if err != nil {
		m.health.Status = "error"
		m.health.Error = err.Error()
		return
	}
	var statuses []localStatus
	if err = json.Unmarshal(statusOutput, &statuses); err != nil || len(statuses) != 1 {
		m.health.Status = "error"
		m.health.Error = "parse Litestream local status"
		return
	}
	if statuses[0].Status != "ok" {
		m.health.Status = "initializing"
		m.health.Error = "Litestream local status is " + statuses[0].Status
		return
	}
	latest := files[0]
	for _, file := range files[1:] {
		if file.MaxTXID > latest.MaxTXID || file.MaxTXID == latest.MaxTXID && file.Timestamp.After(latest.Timestamp) {
			latest = file
		}
	}
	m.health.LocalTXID = statuses[0].LocalTXID
	m.health.ReplicaTXID = latest.MaxTXID
	m.health.RecoveryAt = &latest.Timestamp
	if latest.MaxTXID < statuses[0].LocalTXID {
		m.health.Status = "lagging"
		m.health.Error = "remote replica transaction ID is behind local Litestream state"
		return
	}
	m.health.Status = "ok"
	m.health.Error = ""
	m.health.LastSuccess = &now
}

func (m *Manager) logOutput(stream string, r io.Reader) {
	s := bufio.NewScanner(r)
	s.Buffer(make([]byte, 64*1024), 1024*1024)
	for s.Scan() {
		m.logger.Info("Litestream", "event", "backup.process_output", "result", "observed", "stream", stream, "message", m.redact(s.Text()))
	}
}

func (m *Manager) redact(value string) string {
	for _, name := range []string{"AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "LITESTREAM_ACCESS_KEY_ID", "LITESTREAM_SECRET_ACCESS_KEY", m.cfg.Backup.Continuous.S3.Encryption.CustomerKeyEnv} {
		if name == "" {
			continue
		}
		if secret := os.Getenv(name); secret != "" {
			value = strings.ReplaceAll(value, secret, "[REDACTED]")
		}
	}
	return value
}

func ManagedConfigPath(cfg config.Config, database string) string {
	if cfg.Backup.Continuous.ConfigFile != "" {
		return cfg.Backup.Continuous.ConfigFile
	}
	return database + ".litestream.yml"
}

type litestreamConfig struct {
	Snapshot struct {
		Interval  string `yaml:"interval"`
		Retention string `yaml:"retention"`
	} `yaml:"snapshot"`
	Validation struct {
		Interval string `yaml:"interval"`
	} `yaml:"validation"`
	ShutdownSyncTimeout  string `yaml:"shutdown-sync-timeout"`
	ShutdownSyncInterval string `yaml:"shutdown-sync-interval"`
	Logging              struct {
		Type   string `yaml:"type"`
		Stderr bool   `yaml:"stderr"`
	} `yaml:"logging"`
	DBs []litestreamDB `yaml:"dbs"`
}

type litestreamDB struct {
	Path    string            `yaml:"path"`
	Replica litestreamReplica `yaml:"replica"`
}
type litestreamReplica struct {
	URL                  string `yaml:"url"`
	SyncInterval         string `yaml:"sync-interval"`
	Region               string `yaml:"region,omitempty"`
	Endpoint             string `yaml:"endpoint,omitempty"`
	ForcePathStyle       bool   `yaml:"force-path-style,omitempty"`
	SSEKMSKeyID          string `yaml:"sse-kms-key-id,omitempty"`
	SSECustomerAlgorithm string `yaml:"sse-customer-algorithm,omitempty"`
	SSECustomerKey       string `yaml:"sse-customer-key,omitempty"`
}

func RenderConfig(cfg config.Config, database string) ([]byte, error) {
	b := cfg.Backup.Continuous
	var c litestreamConfig
	c.Snapshot.Interval = b.SnapshotInterval.String()
	c.Snapshot.Retention = b.Retention.String()
	c.Validation.Interval = b.ValidationInterval.String()
	c.ShutdownSyncTimeout = b.ShutdownTimeout.String()
	c.ShutdownSyncInterval = "500ms"
	c.Logging.Type = "json"
	c.Logging.Stderr = true
	r := litestreamReplica{URL: b.ReplicaURL, SyncInterval: b.SyncInterval.String(), Region: b.S3.Region, Endpoint: b.S3.Endpoint, ForcePathStyle: b.S3.ForcePathStyle}
	switch b.S3.Encryption.Mode {
	case "sse-kms":
		r.SSEKMSKeyID = b.S3.Encryption.KMSKeyID
		if r.SSEKMSKeyID == "" {
			r.SSEKMSKeyID = "${" + b.S3.Encryption.KMSKeyIDEnv + "}"
		}
	case "sse-c":
		r.SSECustomerAlgorithm = "AES256"
		r.SSECustomerKey = "${" + b.S3.Encryption.CustomerKeyEnv + "}"
	default:
		return nil, fmt.Errorf("unsupported backup encryption mode %q", b.S3.Encryption.Mode)
	}
	c.DBs = []litestreamDB{{Path: database, Replica: r}}
	return yaml.Marshal(c)
}

func WriteConfig(path string, cfg config.Config, database string) error {
	b, err := RenderConfig(cfg, database)
	if err != nil {
		return err
	}
	b = append([]byte(generatedHeader), b...)
	if existing, readErr := os.ReadFile(path); readErr == nil {
		if !strings.HasPrefix(string(existing), generatedHeader) {
			return fmt.Errorf("refusing to overwrite unmanaged Litestream config %s", path)
		}
		if string(existing) == string(b) {
			return os.Chmod(path, 0o600)
		}
	} else if !errors.Is(readErr, os.ErrNotExist) {
		return readErr
	}
	if err = os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".litestream-*.yml")
	if err != nil {
		return err
	}
	name := tmp.Name()
	ok := false
	defer func() {
		_ = tmp.Close()
		if !ok {
			_ = os.Remove(name)
		}
	}()
	if err = tmp.Chmod(0o600); err != nil {
		return err
	}
	if _, err = tmp.Write(b); err != nil {
		return err
	}
	if err = tmp.Sync(); err != nil {
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	if err = replaceFile(name, path); err != nil {
		return err
	}
	ok = true
	return nil
}

func CheckVersion(ctx context.Context, binary string) (string, error) {
	out, err := runOutput(ctx, binary, "version")
	if err != nil {
		return "", fmt.Errorf("run Litestream version: %w", err)
	}
	match := versionPattern.FindStringSubmatch(string(out))
	if match == nil {
		return "", fmt.Errorf("cannot parse Litestream version from %q", strings.TrimSpace(string(out)))
	}
	version := strings.Join(match[1:4], ".")
	if compareVersion(version, minimumVersion) < 0 {
		return version, fmt.Errorf("Litestream %s is unsupported; version %s or newer is required", version, minimumVersion)
	}
	return version, nil
}

func CheckConfiguration(ctx context.Context, cfg config.Config) error {
	if !cfg.Backup.Continuous.Enabled {
		return nil
	}
	if _, err := CheckVersion(ctx, cfg.Backup.Continuous.Binary); err != nil {
		return err
	}
	database, err := filepath.Abs(cfg.Database.DSN)
	if err != nil {
		return fmt.Errorf("resolve database path: %w", err)
	}
	dir, err := os.MkdirTemp("", "licd-litestream-check-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "litestream.yml")
	if err = WriteConfig(path, cfg, database); err != nil {
		return err
	}
	return checkConfigFile(ctx, cfg.Backup.Continuous.Binary, path)
}

func checkConfigFile(ctx context.Context, binary, path string) error {
	out, err := runOutput(ctx, binary, "databases", "-config", path, "-json")
	if err != nil {
		return fmt.Errorf("Litestream rejected generated configuration: %w", err)
	}
	if !json.Valid(out) {
		return errors.New("Litestream configuration check returned invalid JSON")
	}
	return nil
}

func compareVersion(a, b string) int {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < 3; i++ {
		ai, _ := strconv.Atoi(pa[i])
		bi, _ := strconv.Atoi(pb[i])
		if ai < bi {
			return -1
		}
		if ai > bi {
			return 1
		}
	}
	return 0
}

func runOutput(ctx context.Context, binary string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, binary, args...)
	out, err := cmd.Output()
	if err == nil {
		return out, nil
	}
	var exit *exec.ExitError
	if errors.As(err, &exit) {
		message := strings.TrimSpace(string(exit.Stderr))
		if message != "" {
			return nil, fmt.Errorf("%w: %s", err, message)
		}
	}
	return nil, err
}

type RestoreResult struct {
	Status    string          `json:"status"`
	Output    string          `json:"output,omitempty"`
	Timestamp *time.Time      `json:"timestamp,omitempty"`
	Plan      json.RawMessage `json:"plan,omitempty"`
}

func Restore(ctx context.Context, cfg config.Config, output string, timestamp *time.Time, dryRun bool) (RestoreResult, error) {
	if !cfg.Backup.Continuous.Enabled {
		return RestoreResult{}, errors.New("continuous backup is not enabled")
	}
	if _, err := CheckVersion(ctx, cfg.Backup.Continuous.Binary); err != nil {
		return RestoreResult{}, err
	}
	if output == "" {
		return RestoreResult{}, errors.New("restore output path is required")
	}
	absOutput, err := filepath.Abs(output)
	if err != nil {
		return RestoreResult{}, err
	}
	if _, err = os.Stat(absOutput); err == nil {
		return RestoreResult{}, fmt.Errorf("refusing to overwrite %s", absOutput)
	} else if !errors.Is(err, os.ErrNotExist) {
		return RestoreResult{}, err
	}
	database, err := filepath.Abs(cfg.Database.DSN)
	if err != nil {
		return RestoreResult{}, err
	}
	configDir, err := os.MkdirTemp("", "licd-litestream-restore-")
	if err != nil {
		return RestoreResult{}, err
	}
	defer os.RemoveAll(configDir)
	configPath := filepath.Join(configDir, "litestream.yml")
	if err = WriteConfig(configPath, cfg, database); err != nil {
		return RestoreResult{}, err
	}
	args := []string{"restore", "-config", configPath, "-o", absOutput, "-integrity-check", "full", "-json"}
	if dryRun {
		args = append(args, "-dry-run")
	}
	if timestamp != nil {
		args = append(args, "-timestamp", timestamp.UTC().Format(time.RFC3339Nano))
	}
	args = append(args, database)
	if dryRun {
		plan, runErr := runOutput(ctx, cfg.Backup.Continuous.Binary, args...)
		if runErr != nil {
			return RestoreResult{}, fmt.Errorf("Litestream restore plan: %w", runErr)
		}
		if !json.Valid(plan) {
			return RestoreResult{}, errors.New("Litestream returned an invalid JSON restore plan")
		}
		return RestoreResult{Status: "planned", Output: absOutput, Timestamp: timestamp, Plan: plan}, nil
	}
	if err = os.MkdirAll(filepath.Dir(absOutput), 0o750); err != nil {
		return RestoreResult{}, err
	}
	staging, err := os.CreateTemp(filepath.Dir(absOutput), ".licd-restore-*.db")
	if err != nil {
		return RestoreResult{}, err
	}
	stagingPath := staging.Name()
	_ = staging.Close()
	_ = os.Remove(stagingPath)
	keep := false
	defer func() {
		if !keep {
			_ = os.Remove(stagingPath)
		}
	}()
	for i, arg := range args {
		if i > 0 && args[i-1] == "-o" && arg == absOutput {
			args[i] = stagingPath
		}
	}
	if _, err = runOutput(ctx, cfg.Backup.Continuous.Binary, args...); err != nil {
		return RestoreResult{}, fmt.Errorf("Litestream restore: %w", err)
	}
	verifyCfg := cfg
	verifyCfg.Database.DSN = stagingPath
	repo, err := sqliterepo.Open(verifyCfg)
	if err != nil {
		return RestoreResult{}, fmt.Errorf("open restored database: %w", err)
	}
	verifyErr := repo.Verify(ctx, true)
	closeErr := repo.Close()
	if err = errors.Join(verifyErr, closeErr); err != nil {
		return RestoreResult{}, fmt.Errorf("verify restored database: %w", err)
	}
	if err = os.Rename(stagingPath, absOutput); err != nil {
		return RestoreResult{}, fmt.Errorf("promote restored database: %w", err)
	}
	keep = true
	return RestoreResult{Status: "restored", Output: absOutput, Timestamp: timestamp}, nil
}

type RestorePoint struct {
	Level     int       `json:"level"`
	MinTXID   string    `json:"min_txid"`
	MaxTXID   string    `json:"max_txid"`
	Size      int64     `json:"size"`
	Timestamp time.Time `json:"timestamp"`
}

func RestorePoints(ctx context.Context, cfg config.Config) ([]RestorePoint, error) {
	if !cfg.Backup.Continuous.Enabled {
		return nil, errors.New("continuous backup is not enabled")
	}
	if _, err := CheckVersion(ctx, cfg.Backup.Continuous.Binary); err != nil {
		return nil, err
	}
	database, err := filepath.Abs(cfg.Database.DSN)
	if err != nil {
		return nil, err
	}
	dir, err := os.MkdirTemp("", "licd-litestream-points-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "litestream.yml")
	if err = WriteConfig(path, cfg, database); err != nil {
		return nil, err
	}
	out, err := runOutput(ctx, cfg.Backup.Continuous.Binary, "ltx", "-config", path, "-level", "all", "-json", database)
	if err != nil {
		return nil, fmt.Errorf("list Litestream restore points: %w", err)
	}
	var points []RestorePoint
	if err = json.Unmarshal(out, &points); err != nil {
		return nil, fmt.Errorf("parse Litestream restore points: %w", err)
	}
	return points, nil
}

func minDuration(a, b time.Duration) time.Duration {
	if a < b {
		return a
	}
	return b
}
